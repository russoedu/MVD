func TestResolveSkipsTopicAndDeadLinks(t *testing.T) {
	f := &fakeYouTube{
		pages: map[string]string{"rnlp_avexYQ": watchPage("rnlp_avexYQ", "aNoThErT0p1", "dEsCrIpTi0n")},
		authors: map[string]string{
			"aNoThErT0p1": "Armand Van Helden - Topic",
			"dEsCrIpTi0n": "Armand Van Helden",
		},
	}
	_, res := f.server(t)
	if got, _ := res.Resolve("rnlp_avexYQ"); got != "dEsCrIpTi0n" {
		t.Fatalf("Topic candidate should be skipped in favour of the description link, got %q", got)
	}

	// Candidate that no longer exists, nothing else linked: keep original.
	f = &fakeYouTube{pages: map[string]string{"rnlp_avexYQ": watchPage("rnlp_avexYQ", "gOnEgOnEgOn", "")}}
	_, res = f.server(t)
	if got, _ := res.Resolve("rnlp_avexYQ"); got != "" {
		t.Fatalf("dead candidate must not be returned, got %q", got)
	}

	// Watch page unavailable and next empty: keep original.
	f = &fakeYouTube{}
	_, res = f.server(t)
	if got, _ := res.Resolve("rnlp_avexYQ"); got != "" {
		t.Fatalf("expected empty result, got %q", got)
	}
}

func TestApplyPlaylistFields(t *testing.T) {
	e := PlaylistEntry{
		Playlist:      "90s UK Dance Hits: Vol/1",
		PlaylistTitle: "90s UK Dance Hits: Vol/1",
		PlaylistID:    "PLnEEDxeHD6BPvM-iOmSeKx5N6Uug3vZQa",
		PlaylistIndex: 7,
		PlaylistCount: 90,
	}
	cases := map[string]string{
		"%(playlist_title,playlist)s/%(playlist_index)02d - %(title)s.%(ext)s": "90s UK Dance Hits： Vol⧸1/07 - %(title)s.%(ext)s",
		"%(title)s.%(ext)s": "%(title)s.%(ext)s",
		"%(playlist)s/%(playlist_index)s of %(playlist_count)d.%(ext)s": "90s UK Dance Hits： Vol⧸1/7 of 90.%(ext)s",
		"%(playlist_id)s/%(playlist_index)03d.%(ext)s":                  "PLnEEDxeHD6BPvM-iOmSeKx5N6Uug3vZQa/007.%(ext)s",
		"%(playlist_uploader)s/%(title)s.%(ext)s":                       "%(playlist_uploader)s/%(title)s.%(ext)s",
		"%(playlist_title|Singles)s/%(title)s.%(ext)s":                  "90s UK Dance Hits： Vol⧸1/%(title)s.%(ext)s",
	}
	for in, want := range cases {
		if got := applyPlaylistFields(in, e); got != want {
			t.Errorf("template %q:\n want %q\n got  %q", in, want, got)
		}
	}

	empty := PlaylistEntry{}
	if got := applyPlaylistFields("%(playlist_title|Singles)s/%(playlist_index)02d.%(ext)s", empty); got != "Singles/NA.%(ext)s" {
		t.Errorf("defaults: got %q", got)
	}
}

