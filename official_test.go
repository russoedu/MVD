func TestParseBoolAndConfig(t *testing.T) {
	for _, v := range []string{"true", "True", "yes", "1", "on"} {
		if !parseBool(v) {
			t.Errorf("%q should be true", v)
		}
	}
	for _, v := range []string{"false", "0", "no", "", "maybe"} {
		if parseBool(v) {
			t.Errorf("%q should be false", v)
		}
	}

	dir := t.TempDir()
	path := dir + "/setup.conf"
	if err := os.WriteFile(path, []byte("download_official_music_video = true\nquality=best\n"), 0644); err != nil {
		t.Fatal(err)
	}
	cfg, err := loadSetupConfig(path)
	if err != nil {
		t.Fatal(err)
	}
	if !cfg.DownloadOfficialMusicVideo || cfg.Quality != "best" {
		t.Errorf("unexpected config: %+v", cfg)
	}
	if defaultConfig().DownloadOfficialMusicVideo {
		t.Error("official video mode must be off by default")
	}
}

